// gen_golden.cpp — deterministic generator for int4_golden.txt.
// Usage: gen_golden <output-path>
#include "int4_abi.h"
#include "case_data.h"
#include <cstdio>
#include <cstring>

static void put_hex_bytes(FILE* f, const uint8_t* p, size_t n) {
  for (size_t i = 0; i < n; ++i) fprintf(f, "%02x", p[i]);
  fprintf(f, "\n");
}
static uint32_t fbits(float v) { uint32_t u; std::memcpy(&u, &v, 4); return u; }

int main(int argc, char** argv) {
  if (argc < 2) { fprintf(stderr, "usage: gen_golden <out>\n"); return 1; }
  FILE* f = fopen(argv[1], "w");
  if (!f) return 1;
  fprintf(f, "# int4 golden vectors v1 - Scheme B: (nib - 7.5) * fp16 scale, group 32,\n");
  fprintf(f, "# low nibble first. Generated by gen_golden.cpp; regenerate, never hand-edit.\n");

  // Case 1: raw dequantization of a fixed packed pattern.
  {
    const uint32_t in_dim = 64;
    uint8_t packed[32];
    for (int i = 0; i < 32; ++i) packed[i] = (uint8_t)((i * 37 + 11) & 0xFF);
    uint32_t slots[2] = {0x3C00u, 0x3800u}; // scales 1.0, 0.5 in .x lanes
    fprintf(f, "case dequant_row in_dim=64\nscales 3c00 3800\npacked ");
    put_hex_bytes(f, packed, 32);
    fprintf(f, "expected");
    for (uint32_t lane = 0; lane < in_dim; ++lane) {
      double exact = ((double)int4abi::nibble_at(packed, lane) - 7.5) *
                     (double)int4abi::half_to_float((uint16_t)slots[lane / 32]);
      fprintf(f, " %08x", fbits((float)exact));
    }
    fprintf(f, "\n");
  }

  // Case 2: the shared matvec case.
  {
    auto c = casedata::build_matvec_case();
    fprintf(f, "case matvec in_dim=64 out_dim=4\npacked ");
    put_hex_bytes(f, c.packed.data(), c.packed.size());
    fprintf(f, "scales");
    for (uint32_t s : c.scales) fprintf(f, " %08x", s);
    fprintf(f, "\nx");
    for (float v : c.x) fprintf(f, " %08x", fbits(v));
    fprintf(f, "\nexpected");
    for (double v : c.expected_y) fprintf(f, " %08x", fbits((float)v));
    fprintf(f, "\n");
  }
  fclose(f);
  return 0;
}
