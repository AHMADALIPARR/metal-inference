// gen_kernel_golden.cpp — deterministic generator for
// tests/golden/kernel_golden.txt. Usage: gen_kernel_golden <out>
// Generated, never hand-edit. The construction here MUST match the
// replay in test_kernel_ref.cpp exactly (same LCG seed, same call
// order, same dims) or the bitwise replay fails.
#include "int4_abi.h"
#include "kernel_ref.h"
#include "case_data.h"
#include <cstdio>
#include <cstring>
#include <vector>

static uint32_t fbits(float v) { uint32_t u; std::memcpy(&u, &v, 4); return u; }

int main(int argc, char** argv) {
  if (argc < 2) { fprintf(stderr, "usage: gen_kernel_golden <out>\n"); return 1; }
  FILE* f = fopen(argv[1], "w");
  if (!f) return 1;
  fprintf(f, "# kernel golden vectors v1 - Phase C CPU references.\n");
  fprintf(f, "# Generated by gen_kernel_golden.cpp; regenerate, never hand-edit.\n");

  // Case 1: rmsnorm, x = 1..8, gain 1, eps 1e-5.
  {
    float x[8] = {1, 2, 3, 4, 5, 6, 7, 8}, g[8] = {1, 1, 1, 1, 1, 1, 1, 1}, y[8];
    kref::rmsnorm_ref(x, g, 1.0e-5f, 8, y);
    fprintf(f, "case rmsnorm n=8 eps=1e-5\n");
    fprintf(f, "expected");
    for (int i = 0; i < 8; ++i) fprintf(f, " %08x", fbits(y[i]));
    fprintf(f, "\n");
  }

  // Case 2: composed one-layer decode, tiny dims. Construction mirrors
  // test_kernel_ref.cpp's golden replay exactly.
  {
    kref::LayerDims d;
    d.hidden = 8; d.intermediate = 8; d.q_heads = 2; d.kv_heads = 1;
    d.head_dim = 4; d.context = 16; d.eps = 1.0e-5f;
    casedata::Lcg rng;
    auto make_w = [&](uint32_t rows, uint32_t in) {
      std::vector<uint8_t> pk((size_t)rows * int4abi::packed_row_bytes(in));
      std::vector<uint16_t> sc(rows, 0x3C00);
      for (uint32_t r = 0; r < rows; ++r) {
        std::vector<float> w(in);
        for (auto& v : w) v = rng.next_sym() * 4.0f;
        int4abi::quantize_row_a(w.data(), in, 0x3C00,
                                pk.data() + (size_t)r * int4abi::packed_row_bytes(in));
      }
      return std::pair<std::vector<uint8_t>, std::vector<uint16_t>>{std::move(pk),
                                                                     std::move(sc)};
    };
    auto wq = make_w(8, 8), wk = make_w(4, 8), wv = make_w(4, 8), wo = make_w(8, 8);
    auto wg = make_w(8, 8), wu = make_w(8, 8), wd = make_w(8, 8);
    kref::LayerWeightsA w{wq.first.data(), wq.second.data(),
                          wk.first.data(), wk.second.data(),
                          wv.first.data(), wv.second.data(),
                          wo.first.data(), wo.second.data(),
                          wg.first.data(), wg.second.data(),
                          wu.first.data(), wu.second.data(),
                          wd.first.data(), wd.second.data(),
                          nullptr, nullptr};
    std::vector<float> g1(8, 1.0f), g2(8, 1.0f);
    w.attn_norm_gain = g1.data();
    w.ffn_norm_gain = g2.data();
    std::vector<float> x = {0.1f, -0.2f, 0.3f, 0.0f, 0.5f, -0.1f, 0.2f, -0.4f};
    std::vector<float> kc(16 * 4, 0.0f), vc(16 * 4, 0.0f);
    std::vector<float> scratch(64, 0.0f), out(8);
    kref::decode_layer_ref(x.data(), w, d, 0, kc.data(), vc.data(), out.data(),
                           scratch.data());
    fprintf(f, "case decode_layer hidden=8 inter=8 q=2 kv=1 dh=4 pos=0\n");
    fprintf(f, "expected");
    for (int i = 0; i < 8; ++i) fprintf(f, " %08x", fbits(out[i]));
    fprintf(f, "\n");
  }
  fclose(f);
  return 0;
}
